// Builds the LabSideBar agent tools host plugin into the merged bundle.
// Sources are TypeScript; only the emitted tools.js is loaded at runtime.
import { build } from 'esbuild';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');

await build({
  entryPoints: [path.join(ROOT, 'packages/lab-sidebar/src/tools/index.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  outfile: path.join(ROOT, 'packages/lab-sidebar/tools.js'),
  banner: { js: '// Generated by scripts/build-tools.mjs. Do not edit.' },
});

console.log('packages/lab-sidebar/tools.js');
