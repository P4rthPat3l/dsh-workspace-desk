// Builds the LabSideBar agent tools host half into one ESM entry.
// Sources are TypeScript; only the emitted index.js is loaded at runtime.
import { build } from 'esbuild';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');

await build({
  entryPoints: [path.join(ROOT, 'packages/lab-tools/index.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  outfile: path.join(ROOT, 'packages/lab-tools/index.js'),
  banner: { js: '// Generated by scripts/build-tools.mjs. Do not edit.' },
});

console.log('packages/lab-tools/index.js');
