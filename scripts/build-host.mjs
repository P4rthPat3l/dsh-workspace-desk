// Builds the LabSideBar host half into the package entry point.
// Sources are TypeScript; only the emitted index.js is loaded at runtime.
import { build } from 'esbuild';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');

await build({
  entryPoints: [path.join(ROOT, 'packages/lab-sidebar/src/host/index.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: ['node20'],
  outfile: path.join(ROOT, 'packages/lab-sidebar/index.js'),
  banner: { js: '// Generated by scripts/build-host.mjs. Do not edit.' },
});

console.log('packages/lab-sidebar/index.js');
